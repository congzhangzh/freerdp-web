  const valid = (c) => (c === "en" || c === "zh" ? c : "auto");
  // the language for a choice: "en" or "zh" as chosen; on "auto", the first of the browser's
  // languages that is English or Chinese, English when none is
  function pick(choice, languages) {
    if (choice === "en" || choice === "zh") return choice;
    for (const l of languages || []) {
      const tag = String(l).toLowerCase();
      if (/^en(-|$)/.test(tag)) return "en";
      if (/^zh(-|$)/.test(tag)) return "zh";
    }
    return "en";
  }
  // key in language: its Chinese, or the English given (also for a key the table lacks)
  function translate(lang, key, text, vars) {
    if (lang !== "zh" || !Object.hasOwn(ZH, key)) return text;
    return vars ? ZH[key].replace(/\{(\w+)\}/g, (m, k) => (Object.hasOwn(vars, k) ? String(vars[k]) : m)) : ZH[key];
  }

  const browserLanguages = () => (typeof navigator === "undefined" ? [] : navigator.languages?.length ? navigator.languages : [navigator.language]);
  let choice = "auto";
  try { choice = valid(localStorage.getItem(KEY)); } catch (e) {}
  let lang = pick(choice, browserLanguages());
  const listeners = [];
  const t = (key, text, vars) => translate(lang, key, text, vars);

  // the HTML's own words, before the first change: what English goes back to
  const original = new WeakMap();
  function apply(scope = document) {
    document.documentElement.lang = lang === "zh" ? "zh-Hans" : "en";
    for (const el of scope.querySelectorAll("[data-i18n], [data-i18n-attr], [data-i18n-only]")) {
      let o = original.get(el);
      if (!o) original.set(el, o = { text: el.textContent, attrs: {} });
      if (el.dataset.i18n) el.textContent = t(el.dataset.i18n, o.text);
      for (const pair of (el.dataset.i18nAttr || "").split(",")) {
        const [name, key] = pair.split(":").map((s) => s.trim());
        if (!name || !key) continue;
        if (!(name in o.attrs)) o.attrs[name] = el.getAttribute(name);
        const v = t(key, o.attrs[name]);
        if (v === null) el.removeAttribute(name); else el.setAttribute(name, v);
      }
      if (el.dataset.i18nOnly) el.hidden = el.dataset.i18nOnly !== lang;
    }
  }
  function changed() {
    if (typeof document !== "undefined") {   // not in node's tests
      apply();
      const select = document.getElementById("lang");
      if (select) select.value = choice;
    }
    for (const fn of listeners) try { fn(lang); } catch (e) { console.error(e); }
  }
  function set(c) {
    choice = valid(c);
    try { localStorage.setItem(KEY, choice); } catch (e) {}
    const was = lang;
    lang = pick(choice, browserLanguages());
    if (lang !== was) changed();
  }

  const api = {
    KEY, ZH, pick, translate, t, set,
    get lang() { return lang; },
    get choice() { return choice; },
    // fn(lang) once the page is in a new language (its HTML already is)
    onChange(fn) { listeners.push(fn); },
  };
  root.FreeRDPi18n = api;
  if (typeof module !== "undefined" && module.exports) { module.exports = api; return; }
  // the scripts at the end of the body have run by now and built their parts with t(); in
  // Chinese, the HTML follows, then they redo what they read back from it
  document.addEventListener("DOMContentLoaded", () => {
    if (lang === "zh") changed();
    const select = document.getElementById("lang");
    if (!select) return;
    select.value = choice;
    select.addEventListener("change", () => set(select.value));
  });
